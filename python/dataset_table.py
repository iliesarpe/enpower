"""Statistics of the tabular datasets (Table 1 of the paper).

For each dataset: the size of D_val + D_test (the 25% left out of training by the split of seed
100), the number of classes of the original label, and the number of points of D_val + D_test with
y = 1 (the most frequent class) and y = 0 after binarization, as in train_binary.py.

    python dataset_table.py [--seed 100] [--out ../results/tables]
"""
import argparse
import os

import numpy as np
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# In the order of the table, by size: (OpenML id, name in the table)
DATASETS = [
    (1464, r"Blood Transfusion (\texttt{BTSC})"),
    (31, r"Credit-G (\texttt{CR})"),
    (1468, r"CNAE-9 (\texttt{C9})"),
    (40945, r"Titanic (\texttt{TT})"),
    (1461, r"Bank Marketing (\texttt{BM})"),
    (150, r"Covertype (\texttt{CT})"),
]


def thousands(x):
    s = "{:,}".format(int(x))
    return s.replace(",", r"\,")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=100)
    parser.add_argument("--out", default=os.path.join(REPO, "results", "tables"))
    args = parser.parse_args()

    rows = []
    for data_id, name in DATASETS:
        dataset = fetch_openml(data_id=data_id, as_frame=True, parser="auto")
        y = dataset.target
        y_binary = (y == y.mode()[0]).astype(int).values
        # train_test_split depends only on the number of data points and on the seed, so this
        # split of the indices is the split that train_binary.py applies to the features
        _, held_out = train_test_split(np.arange(len(y_binary)), test_size=0.25, random_state=args.seed)
        yb = y_binary[held_out]
        rows.append((name, len(held_out), y.nunique(), int(yb.sum()), int(len(yb) - yb.sum())))
        print("%-40s |D_val|+|D_test| = %7d, classes = %d, y=1: %d, y=0: %d" % rows[-1])

    lines = ["% generated by python/dataset_table.py, do not edit by hand",
             r"\begin{tabular}{l rrrr}", r"\toprule",
             r"{Dataset (Label)} & $|\dataSetVal|+|\dataSetTra|$ & {Classes} ($\totLabs$) & $y=1$ & $y=0$ \\",
             r"\midrule"]
    for name, size, classes, pos, neg in rows:
        lines.append(r"%s & %s & %d & %s & %s \\" % (name, thousands(size), classes, thousands(pos), thousands(neg)))
    lines += [r"\bottomrule", r"\end{tabular}"]

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "tabular_datasets.tex")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("-> %s" % path)


if __name__ == "__main__":
    main()
